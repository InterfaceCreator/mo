const LAST_NOTE = 'Это была последняя. Всё, что не поместилось в записки, Васин папа хочет сказать тебе сам. Желательно при встрече 🐾';
const TAIL = 3;
const LOVE = new Set([...LOVE_NOTES, LAST_NOTE]);

const shuffle = a => { for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
// очередь одного круга: смешная/романтическая через одну, хвост из трёх романтических — в конце
function makeRound() {
  const fun = shuffle([...FUN_NOTES]), love = shuffle(LOVE_NOTES.slice(0, -TAIL)), q = [];
  for (let i = 0; i < Math.max(fun.length, love.length); i++) { if (fun[i]) q.push(fun[i]); if (love[i]) q.push(love[i]); }
  return [...q, ...LOVE_NOTES.slice(-TAIL)];
}

// следующая записка { t, love } — каждый раз новая; сохранение потом делает вызывающий
export function takeNote(save) {
  let N = save.vasya;
  if (!N) {
    // первый запуск; уже прочитанные по старой схеме — не повторяем в первом круге
    const read = new Set(save.readNotes || []);
    N = save.vasya = { q: makeRound().filter(t => !read.has(t)), i: 0, round: 1, bye: !!save.lastNoteShown };
    delete save.readNotes; delete save.lastNoteType; delete save.lastNoteShown;
  }
  if (N.i >= N.q.length) {
    if (!N.bye) { N.bye = true; return { t: LAST_NOTE, love: true }; }
    N.q = makeRound(); N.i = 0; N.round++;
  }
  const t = N.q[N.i++];
  return { t, love: LOVE.has(t) };
}
// сброс для проверки — всё с нуля, включая прощальную
export function resetNotes(save) { delete save.vasya; delete save.readNotes; delete save.lastNoteType; delete save.lastNoteShown; }

