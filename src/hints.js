const inZone = (z, p) => z.r !== undefined ? Math.hypot(p.x - z.x, p.z - z.z) < z.r : p.x > z.x0 && p.x < z.x1 && p.z > z.z0 && p.z < z.z1;

// что подсказать сейчас (или null). carrying — яйцо в руках
export function hintFor(hero, save, who) {
  const p = hero.pos, id = level.id;
  if (hero.carrying) return id === 'base' ? '🥚 Неси яйцо в загон 🐣 и положи в свободный инкубатор у забора' : id === 'track' ? '🏃 Неси яйцо за линию этого зверя!' : '🏃 С яйцом — бегом к зелёному кругу у портала! Там сторож не догонит';
  for (const n of nests) if (n.has && Math.hypot(p.x - n.x, p.z - n.z) < 5 && Math.abs(p.y - (n.y ?? 0)) < 4) return '🥚 Гнездо: подойди — яйцо прыгнет в руки, и сторож проснётся. Беги к зелёному кругу у портала!';
  for (const z of ZONES[id] || []) if (inZone(z, p)) return typeof z.t === 'function' ? z.t(save, hero, who) : z.t;
  return null;
}
